import assert from 'node:assert/strict';
import {mailView} from './release/web/mail-subscriptions.mjs';
const now=Date.parse('2026-11-04T04:00:00Z');
const row={id:'a'.repeat(32),service:'example.test',amount:null,currency:null,amount_kind:'unknown',renewal_date:'2026-11-03',status:'observed',sources:[{mailbox:'test',date:'2026-11-01T00:00:00Z',ref:'b'.repeat(32),url:null}]};
const data={checked_at:new Date(now).toISOString(),coverage:[{mailbox:'test',status:'partial',history_complete:false}],records:[row]};
let v=mailView(data,now);assert.equal(v.rows[0].amount,null);assert.equal(v.rows[0].upcoming,null);assert.match(v.notice,/неполный/);
assert.doesNotMatch(v.notice,/источник недоступен/);
v=mailView(data,now+90001e3);assert.equal(v.rows[0].stale,true);assert.match(v.notice,/устарела/);
v=mailView(data,now,true);assert.equal(v.rows[0].stale,true);
v=mailView({...data,coverage:[{mailbox:'test',status:'unavailable'}]},now);assert.equal(v.rows[0].stale,true);
assert.match(v.notice,/Не завершён сбор: test/);
console.log('mail view: unknown, stale, past renewal and incomplete coverage passed');
