import assert from 'node:assert/strict';
import {accountView,sortedAccounts,relativeTime,dateLabel} from './release/web/account-view.mjs';
const now=Date.parse('2026-10-30T12:00:00Z'), stamp=new Date(now).toISOString();
const snapshot={observed_at_utc:stamp};
const a={id:'a',label:'Аккаунт A',inventory_present:true,status:'active',disabled:false,unavailable:false,cooldowns:{status:'ok',items:[]},windows:{'15':{failed:0,attempt_records:10}},quota:{observed_at:stamp,windows:[{remaining_percent:57,window_minutes:10080,reset_at:'2026-11-04T09:00:00Z'}]}};
assert.equal(accountView(a,snapshot,now).windows[0].remaining,57);
const zero=structuredClone(a);zero.quota.windows[0].remaining_percent=0;
assert.equal(accountView(zero,snapshot,now).rank,0);
const missing=structuredClone(a);missing.quota.windows[0].remaining_percent=null;
assert.equal(accountView(missing,snapshot,now).windows[0].state,'unknown');
assert.equal(accountView(a,{...snapshot,cache:{stale:true}},now).stateKnown,false);
const old=structuredClone(a);old.quota.observed_at=new Date(now-90000001).toISOString();
assert.equal(accountView(old,snapshot,now).windows[0].remaining,null);
assert.equal(accountView(old,snapshot,now).windows[0].previous,57);
const expired=structuredClone(a);expired.quota.windows[0].reset_at=new Date(now-1).toISOString();
assert.equal(accountView(expired,snapshot,now).windows[0].state,'old');
const failure=structuredClone(a);failure.id='b';failure.label='B';failure.windows['15'].failed=2;
assert.equal(accountView(failure,snapshot,now).status,'Есть ошибки попыток');
assert.deepEqual(accountView(failure,snapshot,now).failures,{failed:2,total:10});
assert.equal(accountView(failure,{...snapshot,cache:{stale:true}},now).failures,null);
assert.equal(accountView({},snapshot,now).stateKnown,false);
assert.equal(accountView({...a,inventory_present:false},snapshot,now).stateKnown,false);
assert.equal(sortedAccounts({...snapshot,accounts:[a,failure]},'',now)[0].account.id,'b');
assert.equal(sortedAccounts({...snapshot,accounts:[a,failure]},'Аккаунт A',now).length,1);
assert.equal(relativeTime('invalid',now),'Время неизвестно');
assert.equal(relativeTime(new Date(now-120000).toISOString(),now),'2 мин назад');
assert.match(dateLabel(stamp),/15:00/);
console.log('16 account-state, quota, ordering and time assertions passed');
